@pytest.mark.asyncio
async def test_create_pull_request():
    service = GitHubService()

    service._post_installation = AsyncMock(
        return_value={
            "number": 42,
            "html_url": (
                "https://github.com/acme/payments-api/pull/42"
            ),
        }
    )

    result = await service.create_pull_request(
        installation_token="installation-token",
        owner="acme",
        repo="payments-api",
        title="feat: integrate stripe",
        body="Generated by AI Integration Engineer.",
        head="agent/stripe-integration",
        base="main",
    )

    assert result["number"] == 42
    assert result["html_url"].endswith("/pull/42")

    service._post_installation.assert_awaited_once_with(
        "/repos/acme/payments-api/pulls",
        "installation-token",
        json={
            "title": "feat: integrate stripe",
            "body": "Generated by AI Integration Engineer.",
            "head": "agent/stripe-integration",
            "base": "main",
        },
    )
