from unittest.mock import AsyncMock, MagicMock, patch

import pytest

from app.services.github_service import GitHubService


@pytest.mark.asyncio
async def test_create_branch():
    service = GitHubService()

    source_ref = {
        "ref": "refs/heads/main",
        "object": {
            "sha": "source-sha-123",
        },
    }

    service.get_branch = AsyncMock(
        return_value=source_ref
    )

    service._post_installation = AsyncMock(
        return_value={
            "ref": "refs/heads/agent/test-branch",
        }
    )

    result = await service.create_branch(
        installation_token="installation-token",
        owner="acme",
        repo="payments-api",
        branch_name="agent/test-branch",
        source_branch="main",
    )

    assert result["ref"] == "refs/heads/agent/test-branch"

    service.get_branch.assert_awaited_once_with(
        installation_token="installation-token",
        owner="acme",
        repo="payments-api",
        branch="main",
    )

    service._post_installation.assert_awaited_once_with(
        "/repos/acme/payments-api/git/refs",
        "installation-token",
        json={
            "ref": "refs/heads/agent/test-branch",
            "sha": "source-sha-123",
        },
    )


@pytest.mark.asyncio
async def test_create_or_update_file():
    service = GitHubService()

    service._put_installation = AsyncMock(
        return_value={
            "content": {
                "path": "src/payment.py",
                "sha": "new-sha",
            }
        }
    )

    result = await service.create_or_update_file(
        installation_token="installation-token",
        owner="acme",
        repo="payments-api",
        path="src/payment.py",
        content="def pay():\n    return True\n",
        branch="agent/stripe-integration",
        message="feat: integrate stripe",
        sha="existing-sha",
    )

    assert result["content"]["sha"] == "new-sha"

    service._put_installation.assert_awaited_once()

    call = service._put_installation.await_args

    assert call.args[0] == (
        "/repos/acme/payments-api/contents/src/payment.py"
    )

    assert call.args[1] == "installation-token"

    payload = call.kwargs["json"]

    assert payload["message"] == "feat: integrate stripe"
    assert payload["branch"] == "agent/stripe-integration"
    assert payload["sha"] == "existing-sha"

    # Verify the content was base64 encoded.
    import base64

    decoded = base64.b64decode(
        payload["content"]
    ).decode("utf-8")

    assert decoded == "def pay():\n    return True\n"


